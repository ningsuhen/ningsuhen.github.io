// Lucide icon sprite for the research design system (public/design-system/) and the report pages (public/research/<slug>/).
// The icons a page uses are every `#i-<name>` it references. This script:
//   1. writes public/design-system/lucide-sprite.svg (union of all referenced icons, for external use);
//   2. rewrites the <!-- lucide-sprite:start --> … <!-- lucide-sprite:end --> block of each design-system page
//      with only that page's symbols, so self-contained pages inline their icons (no request).
// Runs as `prebuild`; idempotent. To add an icon: reference `<use href="#i-<name>"/>` in a page, then run it.
//
// `checkFresh()` is the non-mutating mirror of the design-system bundle's `bundle-fresh` check: it rebuilds
// the sprite in memory and reports any committed file that no longer matches. Wired into check:design-system
// (CI) and the pre-commit hook, so a PR that adds an icon reference but skips `pnpm build` fails instead of
// landing a stale sprite.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { standalonePages } from "./lib/standalone-pages.mjs";

const DIR = path.resolve("public/design-system");
const PUBLIC = path.resolve("public");
const START = "<!-- lucide-sprite:start -->";
const END = "<!-- lucide-sprite:end -->";
const lucide = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/lucide/icons.json", import.meta.url), "utf8"));
const SPRITE_HEAD = "<!-- Lucide icons (ISC licence), generated by scripts/build-lucide-sprite.mjs. Do not edit by hand. -->";

function symbol(name) {
	const icon = lucide.icons[name] ?? (lucide.aliases?.[name] && { ...lucide.icons[lucide.aliases[name].parent], ...lucide.aliases[name] });
	if (!icon) throw new Error(`Lucide icon "${name}" not found in @iconify-json/lucide`);
	const w = icon.width ?? lucide.width ?? 24;
	const h = icon.height ?? lucide.height ?? 24;
	return `<symbol id="i-${name}" viewBox="0 0 ${w} ${h}">${icon.body}</symbol>`;
}

/** The pages this script manages, and the sorted icon names each one references. Drafts are included:
 *  the sprite is regenerated on every build, and a draft page's icons must not 404 while it is reviewed. */
function computeUsed() {
	const pages = [
		...standalonePages({ sections: ["design-system"], depth: 2, drafts: true }),
		...standalonePages({ sections: ["research", "ideas"], depth: 3, drafts: true }),
	];
	const used = new Map(); // page -> sorted icon names
	for (const page of pages) {
		const names = [...new Set([...readFileSync(path.join(PUBLIC, page), "utf8").matchAll(/#i-([a-z0-9-]+)/g)].map((m) => m[1]))].sort();
		used.set(page, names);
	}
	return used;
}

/** Build all outputs. Pure: returns the sprite svg and each page's intended full content, writes nothing. */
export async function build() {
	const used = computeUsed();
	const all = [...new Set([...used.values()].flat())].sort();
	const svg = `${SPRITE_HEAD}\n<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${all.map(symbol).join("\n")}\n</svg>\n`;
	const pages = new Map(); // page -> intended full file content
	for (const [page, names] of used) {
		if (!names.length) continue;
		const src = readFileSync(path.join(PUBLIC, page), "utf8");
		const s = src.indexOf(START);
		const e = src.indexOf(END);
		if (s === -1 || e === -1 || e < s) throw new Error(`${page} uses icons but has no ${START} … ${END} block`);
		const block = `${START}\n<svg style="display:none" aria-hidden="true">\n${names.map(symbol).join("\n")}\n</svg>\n${END}`;
		pages.set(page, src.slice(0, s) + block + src.slice(e + END.length));
	}
	return { svg, pages, count: all.length };
}

/** Write the generated files. */
function write({ svg, pages }) {
	writeFileSync(path.join(DIR, "lucide-sprite.svg"), svg);
	for (const [page, content] of pages) writeFileSync(path.join(PUBLIC, page), content);
}

/** sprite-fresh: the committed sprite files must equal a fresh build from the pages' icon references.
 *  Non-mutating. Returns the list of problems (empty = fresh). Used by the pre-commit hook and check:design-system. */
export async function checkFresh() {
	const { svg, pages } = await build();
	const problems = [];
	const svgPath = path.join(DIR, "lucide-sprite.svg");
	if (!existsSync(svgPath)) problems.push(`public/design-system/lucide-sprite.svg is missing (run pnpm build)`);
	else if (readFileSync(svgPath, "utf8") !== svg) problems.push(`public/design-system/lucide-sprite.svg is stale: it differs from a fresh build (run pnpm build)`);
	for (const [page, content] of pages) {
		const p = path.join(PUBLIC, page);
		if (readFileSync(p, "utf8") !== content) problems.push(`public/${page} is stale: its Lucide sprite block differs from a fresh build (run pnpm build)`);
	}
	return { problems };
}

async function main() {
	const check = process.argv.includes("--check");
	if (check) {
		const { problems } = await checkFresh();
		if (problems.length) {
			console.error(`Lucide sprite not fresh:\n${problems.map((p) => `  - ${p}`).join("\n")}`);
			process.exit(1);
		}
		console.log("Lucide sprite fresh");
		return;
	}
	const { svg, pages, count } = await build();
	write({ svg, pages });
	console.log(`lucide sprite: ${count} icon(s) -> public/design-system/lucide-sprite.svg; inlined in ${pages.size} page(s): ${[...pages.keys()].join(", ")}`);
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) main();
